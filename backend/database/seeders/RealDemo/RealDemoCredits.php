<?php

namespace Database\Seeders\RealDemo;

/**
 * Renders `assets/real-demo/CREDITS.md` from the demo data file: the photos are used straight from
 * Wikimedia Commons, so each one keeps its page, author and license in the repository.
 */
final class RealDemoCredits
{
    public const FILE = 'seeders/assets/real-demo/CREDITS.md';

    /**
     * @param  list<array<string, mixed>>  $models
     */
    public static function render(array $models): string
    {
        $text = "# Real demo photo credits\n\n"
            ."The demo vehicles point at these photos on Wikimedia Commons; nothing is uploaded.\n"
            ."Generated by `php artisan demo:reales-creditos` from `models.json`. Do not edit by hand.\n";

        foreach ($models as $model) {
            $text .= "\n## {$model['make']} {$model['model']}\n\n";
            foreach ($model['photos'] as $photo) {
                $text .= "- [{$photo['page']}]({$photo['page']}) by {$photo['author']}, {$photo['license']}\n";
            }
        }

        return $text;
    }
}
